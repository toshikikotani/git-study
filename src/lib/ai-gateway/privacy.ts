/**
 * AIへ送る前のPIIマスキング(N1本人要件「カード番号や電話番号などの個人情報は
 * マスクする」)。
 *
 * この家計簿アプリのドメインデータ(店名・品目名・金額・日付)自体には、
 * カード番号や電話番号は元々含まれない(payment_method は種別の enum で、
 * カード番号そのものを保持する列はスキーマに存在しない)。それでも、本人が
 * チャット(N7)や自然文入力(N3)へ自由に書く文章、レシートのOCR生テキストには
 * 稀に紛れ得るため、AIへ渡す本文を組み立てる直前に通す防御的な処理として置く。
 */

// 13〜19桁の連続した数字(区切りにスペース/ハイフンを許す)。クレジットカード番号の桁数。
const CARD_NUMBER_PATTERN = /\b(?:\d[ -]?){13,19}\b/g;
// 0で始まる日本の電話番号(市外局番-市内局番-加入者番号、区切り任意)。
const PHONE_PATTERN = /\b0\d{1,4}[ -]?\d{1,4}[ -]?\d{3,4}\b/g;

export function maskPii(text: string): string {
  return text
    .replace(CARD_NUMBER_PATTERN, '[カード番号を非表示]')
    .replace(PHONE_PATTERN, '[電話番号を非表示]');
}
