/**
 * 日本の祝日(予測モデルの曜日効果を補正する弱いシグナル用、M2)。
 *
 * 判断:春分・秋分・敬老の日・海の日・スポーツの日・成人の日のような
 * 「移動の祝日」(天文計算・ハッピーマンデー制度が要る)は対象外にし、
 * 日付が固定の祝日だけを対象にした(docs/decisions.md に記録)。曜日・祝日の
 * 係数はどちらも1.0へ縮小推定するため、この簡略化で数件の祝日を見落としても
 * 影響は小さい。振替休日も対象外。
 */

const FIXED_HOLIDAYS = new Set([
  '01-01', // 元日
  '02-11', // 建国記念の日
  '02-23', // 天皇誕生日
  '05-03', // 憲法記念日
  '05-04', // みどりの日
  '05-05', // こどもの日
  '08-11', // 山の日
  '11-03', // 文化の日
  '11-23', // 勤労感謝の日
]);

/** DateOnly('YYYY-MM-DD') が固定日の祝日かどうか。 */
export function isFixedHoliday(dateOnly: string): boolean {
  return FIXED_HOLIDAYS.has(dateOnly.slice(5));
}
